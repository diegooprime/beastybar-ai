#!/usr/bin/env node
// Plays games between the engine's built-in agents in site/bb.wasm and writes the ones worth watching to
// site/games.js. A game is stored as its deal seed, who started and the moves, so the site replays it through the
// same engine. For search players, the value the search gave every legal move is kept as well.
// Run: node scripts/site_games.mjs [--deals N]
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {load} from "../site/engine.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const engine = await load(readFileSync(join(root, "site/bb.wasm")));

const AGENTS = {
  pimc8: {kind: "pimc", worlds: 128, depth: 8},
  pimc4: {kind: "pimc", worlds: 8, depth: 4},
  greedy: {kind: "greedy"},
  random: {kind: "random"},
};
// [player A, player B, deals to play, games to keep]
const MATCHUPS = [["pimc8", "pimc8", 40, 8], ["pimc8", "pimc4", 20, 5], ["pimc8", "greedy", 12, 4], ["greedy", "random", 12, 3]];
const arg = process.argv.indexOf("--deals");
const scale = arg > 0 ? Number(process.argv[arg + 1]) / 40 : 1;

function play(seed, start, seats) {
  let s = engine.newGame(seed, start);
  const moves = [], vals = [], lead = [];
  while (!s.over) {
    const spec = AGENTS[seats[s.toMove]];
    const {action, values} = engine.think(spec, seed * 64 + moves.length + 1);
    vals.push(spec.kind === "pimc" ? Object.entries(values).flatMap(([a, v]) => [Number(a), Math.round(v * 100) / 100]) : null);
    moves.push(action);
    s = engine.apply(action);
    lead.push(Math.sign(s.scores[0] - s.scores[1]));
  }
  return {seed, start, p: seats, moves, vals, score: s.scores, lead};
}

function describe(g) {
  const tags = [], [a, b] = g.score, winner = Math.sign(a - b);
  let changes = 0, last = 0, behind = false;
  for (const l of g.lead) {
    if (l && last && l !== last) changes++;
    if (l) last = l;
    if (winner && l === -winner) behind = true;
  }
  const late = g.lead.length - g.lead.findLastIndex(l => l !== winner) - 1;   // plies the winner led to the end
  if (!winner) tags.push("draw");
  else if (late <= 2) tags.push("decided on the last cards");
  else if (behind) tags.push("comeback");
  if (winner && Math.min(a, b) === 0) tags.push("shutout");
  if (changes >= 3) tags.push(changes + " lead changes");
  const drama = changes * 3 + (winner === 0 ? 4 : 0) + (late <= 2 ? 4 : 0) + (behind ? 2 : 0) - Math.abs(a - b) * 0.3;
  return {tags, drama};
}

const out = [];
for (const [a, b, deals, keep] of MATCHUPS) {
  const games = [], n = Math.max(keep, Math.round(deals * scale));
  for (let i = 0; i < n; i++) {
    const seed = 20261013 + out.length * 1000 + i;
    // Duplicate deal pair: the same deal with seats swapped.
    for (const seats of a === b ? [[a, b]] : [[a, b], [b, a]]) games.push(play(seed, i & 1, seats));
  }
  const ranked = games.map(g => ({g, ...describe(g)})).sort((x, y) => y.drama - x.drama).slice(0, keep);
  for (const {g, tags} of ranked) out.push({id: out.length + 1, seed: g.seed, start: g.start, p: g.p, moves: g.moves, vals: g.vals, score: g.score, tags});
  const wins = games.reduce((w, g) => w + (g.p[0] === a ? Math.sign(g.score[0] - g.score[1]) : Math.sign(g.score[1] - g.score[0])), 0);
  console.error(`${a} vs ${b}: ${games.length} games, net wins for ${a}: ${wins}, kept ${ranked.length}`);
}
writeFileSync(join(root, "site/games.js"),
  "// Generated by scripts/site_games.mjs: games played by the engine's built-in agents in site/bb.wasm. Do not edit.\n" +
  "export const GAMES = " + JSON.stringify(out) + ";\n");
console.error(`site/games.js: ${out.length} games`);
