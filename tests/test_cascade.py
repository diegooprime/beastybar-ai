"""Cascade labels (bbar/value/cascade.py): depth-limited labels valued by a network, and the training cascade.

- The label: with exact leaf values (dl.LeafOracle through solve_external, dl.ExactValues through the batched
  label_many) a cascade label's game value and range-weighted values equal bbar.value.gen's exact label of the same PBS
  within solver tolerance; per hand only where the ranges reach. Observed with full-support Dirichlet ranges (gen
  solved to 1e-8): range-weighted |diff| 5.5e-5 / max over hands 1.1e-3 (golden game 5, ply 11, leaves at 13, 200
  iterations: the slow CFR-D case), 6e-9 (game 5, ply 12, leaves at 14) and 1.9e-7 (game 3, ply 12, leaves at 13);
  game values within 2e-7. Off the ranges' support it is not gen's label, at any iteration count (sparse ranges:
  0.25 for hands with no mass at golden game 1, ply 12, at 200 and 800 iterations, while the hands with mass agree to
  1e-6 and 1e-8); with Dirichlet-0.1 ranges the hands with tiny mass converge slowest. So cascade shards say
  all_hands_exact = false and bbar.value.train leaves them out of its all-hands term.
- solve_many: lockstep solves equal one-at-a-time solves (same value function).
- The CLI writes gen.py's shard format (trainable together with exact shards), exactly --labels labels, and reports
  labels/s; the driver trains, labels a level, retrains on everything and moves down; --resume skips only trainings
  that ran to their end and levels generated by the current network, and redoes everything after a redone step.
"""
import json
import shlex
from pathlib import Path

import numpy as np
import pytest

core = pytest.importorskip("bbar._core")
torch = pytest.importorskip("torch")

from bbar import window_check  # noqa: E402
from bbar.golden import load  # noqa: E402
from bbar.value import cascade, gen, pbs, train  # noqa: E402
from bbar.value import dl as D  # noqa: E402
from bbar.value.net import NetValues, ValueNet  # noqa: E402

Window = core.Window
GEN = ["--workers", "1", "--blueprint", "", "--mix", "random:1"]


@pytest.fixture(scope="module")
def games():
    return load()


def full_support(G, seed):
    w0 = Window(G)
    rng = np.random.default_rng(seed)
    out = []
    for p in range(2):
        r = np.zeros(495)
        h = w0.hands(p)
        r[h] = rng.dirichlet(np.ones(len(h)))
        out.append((r, "dirichlet1"))
    return out


def compare(lab, exact):
    feas = pbs.masks_of_keys([exact["key"]])[0]
    diff = np.abs(lab["values"] - exact["values"])
    assert lab["key"] == exact["key"] and lab["start"] == exact["start"]
    assert np.allclose(lab["ranges"], exact["ranges"], atol=1e-12)
    assert np.all(lab["values"][~feas] == 0)
    return (exact["ranges"] * diff).sum() / 2, diff[feas].max(), abs(lab["game_value"] - exact["game_value"])


@pytest.mark.parametrize("gi,ply,d,iters,tol,oracle", [(5, 12, 2, 200, 1e-6, True), (3, 12, 1, 200, 2e-6, True),
                                                      (5, 11, 2, 200, 2e-4, False)])
def test_cascade_label_is_the_exact_label_with_exact_leaves(games, gi, ply, d, iters, tol, oracle):
    G = window_check.public_game(games[gi], ply)
    rk = full_support(G, gi)
    (exact,), _ = gen.label_state(G, 0, np.random.default_rng(0), 1e-8, 100_000, first=rk)
    assert exact["exploitability"] <= 1e-8
    # The batched path (solve_many, as the CLI runs it) with the exact value function.
    (lab,), st = cascade.label_many([(G, ply, rk)], D.ExactValues(target=1e-8), d, 15, iters)
    rw, mx, gv = compare(lab, exact)
    assert rw <= tol and gv <= 5e-6 and mx <= 25 * tol, (rw, mx, gv)
    assert lab["iterations"] == iters and lab["exploitability"] < 1e-4 and st["calls"] == 2 * iters
    if not oracle:      # (the slow case: the batched path only)
        return
    # One window with dl.LeafOracle through solve_external: the same label.
    dl = Window(G, rk[0][0], rk[1][0], leaf_ply=ply + d)
    dl.solve_external(D.LeafOracle(dl, target=1e-8), iters=iters)
    lab2 = cascade.label_solved(dl, G, ["dirichlet1"] * 2, iters, 0.0)
    rw2, _, gv2 = compare(lab2, exact)
    assert rw2 <= tol and gv2 <= 5e-6
    assert np.abs(lab2["values"] - lab["values"]).max() < 1e-4


@pytest.mark.parametrize("gi,kind", [(1, "sparse"), (0, "dirichlet0.1")])
def test_cascade_labels_match_on_the_ranges_not_off_them(games, gi, kind):
    """Sparse and Dirichlet-0.1 ranges (gen.py's family): game value, range-weighted values and the values of hands
    with real mass are gen.py's; hands with no mass are not, and more iterations do not change that."""
    ply = 12
    G = window_check.public_game(games[gi], ply)
    _, _, u, _, _ = pbs.decode_keys([core.public_key(G)])
    rng = np.random.default_rng(gi)
    rk = [pbs.sample_range(u[0, p], rng, kind) for p in (0, 1)]
    (exact,), _ = gen.label_state(G, 0, rng, 1e-8, 100_000, first=rk)
    feas = pbs.masks_of_keys([exact["key"]])[0]
    r = exact["ranges"]
    off = []
    for iters, tol in [(200, 1e-5), (800, 5e-6)]:
        (lab,), _ = cascade.label_many([(G, ply, rk)], D.ExactValues(target=1e-8), 2, 15, iters)
        rw, _, gv = compare(lab, exact)
        diff = np.abs(lab["values"] - exact["values"])
        assert rw <= tol and gv <= tol, (iters, rw, gv)
        assert diff[feas & (r >= 1e-2)].max() <= 20 * tol, iters      # hands the ranges hold
        off.append(diff[feas & (r == 0)].max(initial=0.0))
    if kind == "sparse":     # hands outside the support: not gen.py's labels, at any iteration count
        assert off[0] > 0.1 and off[1] > 0.1, off


def test_lockstep_solves_equal_single_solves(games):
    v = ValueNet(width=16, blocks=1)
    nv = NetValues(v, chunk=64)
    items = []
    for gi, ply in [(1, 10), (2, 11), (4, 12)]:
        G = window_check.public_game(games[gi], ply)
        items.append((G, ply, full_support(G, gi)))
    labs, st = cascade.label_many(items, nv, 2, 15, 20, threads=2)
    assert st["leaves"] > 0 and st["calls"] == 40
    for (G, ply, rk), lab in zip(items, labs):
        dl = Window(G, rk[0][0], rk[1][0], leaf_ply=ply + 2)
        dl.solve_external(D.NetLeaf(dl, nv), iters=20)
        one = cascade.label_solved(dl, G, ["dirichlet1"] * 2, 20, 0.0)
        assert np.array_equal(one["values"], lab["values"]) and one["game_value"] == lab["game_value"]


def tiny_value(path):
    torch.manual_seed(0)
    v = ValueNet(width=16, blocks=1)
    torch.save(dict(model=v.state_dict(), hparams=v.hparams, pbs_version=pbs.PBS_VERSION), path)
    return str(path)


def test_cascade_labels_train_with_exact_labels(tmp_path):
    net = tiny_value(tmp_path / "v.pt")
    exact, casc = tmp_path / "exact", tmp_path / "casc"
    gen.main(["--out", str(exact), *GEN, "--plies", "12", "--ply-weights", "1", "--labels", "8",
              "--ranges-per-state", "2"])
    args = ["--net", net, "--out", str(casc), *GEN, "--plies", "10,11", "--ply-weights", "1,1", "--labels", "6",
            "--ranges-per-state", "2", "--d", "2", "--max-leaf-ply", "12", "--iters", "5", "--jobs", "4",
            "--shard-size", "4", "--threads", "2"]
    s = cascade.main(["labels", *args])
    assert s["labels"] == 6 and s["kind"] == "cascade-labels" and s["labels_per_sec"] > 0   # exactly --labels
    assert s["all_hands_exact"] is False and s["net_sha256"] == gen._sha(net)
    assert {r["ply"]: r["leaf_ply"] for r in s["by_ply"]} == {10: 12, 11: 12}
    assert s["command"].startswith("python -m bbar.value.cascade labels --net")
    d, paths = train.load_labels([str(exact), str(casc)])
    assert sorted(set(d["ply"].tolist())) == [10, 11, 12] and len(d["key"]) == 8 + s["labels"]
    assert np.all(d["values"][~d["mask"]] == 0) and np.allclose(d["ranges"].sum(-1), 1, atol=1e-5)
    with np.load(next(p for p in paths if "/casc/" in p)) as z:
        meta = json.loads(z["meta"].item())
        assert meta["kind"] == "cascade-labels" and meta["config"]["iters"] == 5 and meta["net_sha256"]
        assert meta["all_hands_exact"] is False
    # Only the exact labels' off-range values train (the all-hands term); cascade labels train on their ranges.
    assert np.array_equal(d["all_exact"], d["ply"] == 12)
    w = train.all_weights(d["all_exact"], 0.1, 0.0)
    assert np.all(w[d["all_exact"]] == 0.1) and np.all(w[~d["all_exact"]] == 0)
    rows = ~d["all_exact"]
    t = {k: torch.as_tensor(d[k][rows]) for k in ("ranges", "values", "mask")}
    r = t["ranges"].clone()
    r[..., ::2] = 0                                     # (ranges with hands off their support)
    r = r / r.sum(-1, keepdim=True)
    pred = torch.rand(t["values"].shape, generator=torch.Generator().manual_seed(0))
    moved = t["values"].clone()
    off = (r == 0) & t["mask"]
    moved[off] = 1 - moved[off]                         # every label off the ranges
    w = torch.as_tensor(w[rows])
    assert train.losses(pred, t["values"], r, t["mask"], 0.1, w) == train.losses(pred, moved, r, t["mask"], 0.1, w)
    assert train.losses(pred, t["values"], r, t["mask"], 0.1, 0.1) != train.losses(pred, moved, r, t["mask"], 0.1,
                                                                                    0.1)
    with pytest.raises(SystemExit):     # a level must lie below the leaves
        cascade.main(["labels", *args[:-2], "--plies", "12", "--force"])
    # Fewer labels than --jobs: a single cut batch; and the split over workers is exact.
    s2 = cascade.main(["labels", *args, "--labels", "3", "--force"])
    assert s2["labels"] == 3 and len(train.load_labels([str(casc)])[0]["key"]) == 3
    assert [cascade.worker_quota(10, 4, w) for w in range(4)] == [3, 3, 2, 2]


def test_cascade_driver(tmp_path, monkeypatch):
    monkeypatch.setattr(cascade, "ROOT", tmp_path)
    monkeypatch.setattr(train, "ROOT", tmp_path)
    exact = tmp_path / "data" / "value" / "exact"
    gen.main(["--out", str(exact), *GEN, "--plies", "12,13", "--ply-weights", "1,1", "--labels", "40",
              "--ranges-per-state", "2"])
    targs = ("--steps 4 --batch 8 --width 16 --blocks 1 --warmup 1 --eval-every 2 --log-every 2 "
             "--val-permille 300 --test-permille 0")
    largs = shlex.join([*GEN, "--ranges-per-state", "2", "--jobs", "4"])
    run = ["run", "--name", "c", "--data", str(exact), "--levels", "11:6", "10:6", "--d", "2", "--max-leaf-ply", "12",
           "--iters", "4", "--workers", "1", "--threads", "1", "--train-args", targs, "--label-args", largs]
    net, log = cascade.main(run)
    ck = tmp_path / "checkpoints" / "value"
    assert net == str(ck / "c-2" / "best.pt")
    assert [x["level"] for x in log] == [[11], [10]]
    assert log[0]["net"].endswith("c-0/best.pt") and log[1]["net"].endswith("c-1/best.pt")
    lines = (tmp_path / "runs" / "value" / "c-2" / "metrics.jsonl").read_text().splitlines()
    assert len(json.loads(lines[0])["data_files"]) >= 3     # exact + both levels
    assert json.loads(lines[-1])["kind"] == "done" and all(train.is_complete(ck / f"c-{k}" / "best.pt")
                                                           for k in range(3))
    summary = json.loads((tmp_path / "data" / "value" / "c-p11" / "summary-s0.json").read_text())
    assert summary["net_sha256"] == gen._sha(ck / "c-0" / "best.pt")     # the level's generating network

    trained = []
    real_train = train.main

    def spy(argv):
        trained.append(argv[argv.index("--name") + 1])
        return real_train(argv)
    monkeypatch.setattr(train, "main", spy)

    def resume():
        trained.clear()
        return cascade.main([*run, "--resume"])

    # --resume skips everything that ran to its end.
    net2, log2 = resume()
    assert net2 == net and log2 == [] and trained == []
    # A training interrupted after its first best.pt (written at every validation improvement) is not finished...
    (ck / "c-1" / "best.pt").unlink()
    real_save = train.save_atomic

    def interrupt(obj, path):
        real_save(obj, path)
        if Path(path).name == "best.pt" and Path(path).parent.name == "c-1":
            raise KeyboardInterrupt
    monkeypatch.setattr(train, "save_atomic", interrupt)
    with pytest.raises(KeyboardInterrupt):
        resume()
    monkeypatch.setattr(train, "save_atomic", real_save)
    assert (ck / "c-1" / "best.pt").is_file() and not train.is_complete(ck / "c-1" / "best.pt")
    # ... so a rerun trains it again, then everything that depends on it; the steps before stay.
    net3, log3 = resume()
    assert trained == ["c-1", "c-2"] and [x["level"] for x in log3] == [[10]]
    assert train.is_complete(ck / "c-1" / "best.pt")
    # A level generated by another network than the current one is generated again.
    c0 = torch.load(ck / "c-0" / "best.pt", weights_only=False)
    c0["model"] = {k: v + 0.01 for k, v in c0["model"].items()}
    torch.save(c0, ck / "c-0" / "best.pt")
    _, log4 = resume()
    assert trained == ["c-1", "c-2"] and [x["level"] for x in log4] == [[11], [10]]
    assert log4[0]["net"].endswith("c-0/best.pt")
    with pytest.raises(ValueError):
        cascade.parse_levels(["8,9:10", "9:10"])
